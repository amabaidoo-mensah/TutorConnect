create table if not exists public.course_catalogue_requests (
  id bigint generated by default as identity primary key,
  institution_id int not null references public.institutions(id) on delete cascade,
  requested_by uuid not null references public.profiles(id) on delete cascade,
  code text not null check (char_length(trim(code)) between 1 and 40),
  title text not null check (char_length(trim(title)) between 1 and 200),
  academic_unit_id int references public.academic_units(id) on delete set null,
  source_url text check (
    source_url is null
    or (source_url ~* '^https://[^[:space:]]+$' and char_length(source_url) <= 2048)
  ),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  admin_note text check (admin_note is null or char_length(admin_note) <= 1000),
  course_id int references public.courses(id) on delete set null,
  reviewed_by uuid references public.profiles(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists course_catalogue_requests_owner_idx
  on public.course_catalogue_requests(requested_by, created_at desc);

create index if not exists course_catalogue_requests_pending_idx
  on public.course_catalogue_requests(institution_id, created_at)
  where status = 'pending';

create unique index if not exists course_catalogue_requests_pending_code_idx
  on public.course_catalogue_requests(institution_id, requested_by, upper(trim(code)))
  where status = 'pending';

alter table public.course_catalogue_requests enable row level security;

create policy "course catalogue requests read own or admin"
  on public.course_catalogue_requests
  for select to authenticated
  using (requested_by = auth.uid() or is_admin());

create policy "course catalogue requests insert tutor"
  on public.course_catalogue_requests
  for insert to authenticated
  with check (
    requested_by = auth.uid()
    and status = 'pending'
    and course_id is null
    and reviewed_by is null
    and reviewed_at is null
    and admin_note is null
    and exists (
      select 1
      from public.profiles p
      where p.id = auth.uid()
        and p.role = 'tutor'
        and p.account_status = 'active'
    )
    and exists (
      select 1
      from public.institutions i
      where i.id = institution_id and i.active
    )
    and (
      academic_unit_id is null
      or exists (
        select 1
        from public.academic_units unit
        where unit.id = course_catalogue_requests.academic_unit_id
          and unit.institution_id = course_catalogue_requests.institution_id
          and unit.active
      )
    )
  );

grant select, insert on public.course_catalogue_requests to authenticated;
grant usage, select on sequence public.course_catalogue_requests_id_seq to authenticated;

create or replace function public.admin_review_course_catalogue_request(
  p_request bigint,
  p_status text,
  p_reason text,
  p_source_url text default null
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  request_row public.course_catalogue_requests%rowtype;
  verified_source text;
  target_course_id int;
  target_course_active boolean;
  target_course_title text;
  target_academic_unit_id int;
begin
  if not is_admin() then raise exception 'admin only'; end if;
  if p_status is null or p_status not in ('approved', 'rejected') then raise exception 'invalid catalogue request status'; end if;
  if char_length(trim(coalesce(p_reason, ''))) not between 4 and 1000 then raise exception 'moderator reason must be between 4 and 1000 characters'; end if;

  select * into request_row
  from public.course_catalogue_requests
  where id = p_request
  for update;
  if not found then raise exception 'catalogue request not found'; end if;
  if request_row.status <> 'pending' then raise exception 'catalogue request has already been reviewed'; end if;

  if p_status = 'approved' then
    verified_source := coalesce(nullif(trim(p_source_url), ''), request_row.source_url);
    if verified_source is null
      or verified_source !~* '^https://[^[:space:]]+$'
      or char_length(verified_source) > 2048 then
      raise exception 'an official HTTPS course outline or teaching schedule is required to approve';
    end if;
    if request_row.academic_unit_id is not null and not exists (
      select 1
      from public.academic_units unit
      where unit.id = request_row.academic_unit_id
        and unit.institution_id = request_row.institution_id
        and unit.active
    ) then
      raise exception 'the selected academic unit is not active for this institution';
    end if;

    select id, active, title, academic_unit_id
    into target_course_id, target_course_active, target_course_title, target_academic_unit_id
    from public.courses
    where institution_id = request_row.institution_id
      and upper(trim(code)) = upper(trim(request_row.code))
    order by id
    limit 1
    for update;

    if target_course_id is null then
      insert into public.courses(institution_id, code, title, academic_unit_id, source_url)
      values (
        request_row.institution_id,
        upper(trim(request_row.code)),
        trim(request_row.title),
        request_row.academic_unit_id,
        verified_source
      )
      on conflict (institution_id, code) do nothing
      returning id, active, title, academic_unit_id
      into target_course_id, target_course_active, target_course_title, target_academic_unit_id;

      if target_course_id is null then
        select id, active, title, academic_unit_id
        into target_course_id, target_course_active, target_course_title, target_academic_unit_id
        from public.courses
        where institution_id = request_row.institution_id
          and upper(trim(code)) = upper(trim(request_row.code))
        order by id
        limit 1
        for update;
      end if;
    end if;

    if target_course_id is null then raise exception 'course could not be added to the catalogue'; end if;
    if not coalesce(target_course_active, true) then raise exception 'an inactive course already uses this code'; end if;
    if upper(trim(target_course_title)) <> upper(trim(request_row.title)) then
      raise exception 'this course code already exists with a different title';
    end if;
    if request_row.academic_unit_id is not null
      and target_academic_unit_id is distinct from request_row.academic_unit_id then
      raise exception 'this course code already exists under a different academic unit';
    end if;

    insert into public.tutor_courses(tutor_id, course_id, status)
    values (request_row.requested_by, target_course_id, 'pending')
    on conflict (tutor_id, course_id) do nothing;
  end if;

  update public.course_catalogue_requests
  set status = p_status,
      source_url = case when p_status = 'approved' then verified_source else source_url end,
      course_id = case when p_status = 'approved' then target_course_id else null end,
      admin_note = trim(p_reason),
      reviewed_by = auth.uid(),
      reviewed_at = now()
  where id = request_row.id;

  insert into public.admin_actions(admin_id, target_id, action, reason)
  values (
    auth.uid(),
    request_row.requested_by,
    'Catalogue course request ' || p_status || ': ' || request_row.code,
    trim(p_reason)
  );
end
$$;

revoke all on function public.admin_review_course_catalogue_request(bigint, text, text, text) from public;
grant execute on function public.admin_review_course_catalogue_request(bigint, text, text, text) to authenticated;
